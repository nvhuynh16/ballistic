// =============================================================================
// Epoch Reference Data Structure
// =============================================================================

struct EpochRefData {
    std::string name;
    double UTC_JD, TT_JD, UT1_JD, T_TT;
    double UT1_UTC, XP_RAD, YP_RAD;
    double L, LP, F, D, OM;
    double L_ME, L_VE, L_E, L_MA, L_J, L_SA, L_U, L_NE, PA;
    double GAMB, PHIB, PSIB, EPSA;
    double DPSI, DEPS;
    double CIP_X, CIP_Y;
    double S, ERA, SP;
    double GMST, GAST;
    std::array<double, 9> NPB_MATRIX;
    std::array<double, 9> Q_MATRIX;
    std::array<double, 9> W_MATRIX;
    std::array<double, 9> GCRS_TO_ITRF;
};

// =============================================================================
// Validation for a single epoch (returns the number of quantities out of tolerance)
// =============================================================================

int validate_epoch(const EpochRefData& ref) {
    int failures = 0;
    auto check = [&](const std::string& name, double expected, double actual, double tolerance) {
        double diff = std::abs(expected - actual);
        if (diff > tolerance) {
            failures++;
            std::cout << "  FAIL: " << name << std::endl;
            std::cout << "    Expected: " << std::scientific << std::setprecision(15) << expected << std::endl;
            std::cout << "    Actual:   " << actual << std::endl;
            std::cout << "    Diff:     " << diff << " (tol: " << tolerance << ")" << std::endl;
        }
    };

    double t_tt = ref.T_TT;
    double ut1_jd = ref.UT1_JD;

    // 1. Fundamental Arguments
    auto args = coords::compute_fundamental_args(t_tt);
    check(ref.name + ": l", ref.L, args.l, tolerances::FUNDAMENTAL_ARGS);
    check(ref.name + ": l'", ref.LP, args.lp, tolerances::FUNDAMENTAL_ARGS);
    check(ref.name + ": F", ref.F, args.F, tolerances::FUNDAMENTAL_ARGS);
    check(ref.name + ": D", ref.D, args.D, tolerances::FUNDAMENTAL_ARGS);
    check(ref.name + ": Om", ref.OM, args.Om, tolerances::FUNDAMENTAL_ARGS);

    // 2. Planetary Longitudes
    check(ref.name + ": L_Me", ref.L_ME, args.L_Me, tolerances::PLANETARY_LONGITUDES);
    check(ref.name + ": L_Ve", ref.L_VE, args.L_Ve, tolerances::PLANETARY_LONGITUDES);
    check(ref.name + ": L_E", ref.L_E, args.L_E, tolerances::PLANETARY_LONGITUDES);
    check(ref.name + ": L_Ma", ref.L_MA, args.L_Ma, tolerances::PLANETARY_LONGITUDES);
    check(ref.name + ": L_J", ref.L_J, args.L_J, tolerances::PLANETARY_LONGITUDES);
    check(ref.name + ": L_Sa", ref.L_SA, args.L_Sa, tolerances::PLANETARY_LONGITUDES);
    check(ref.name + ": L_U", ref.L_U, args.L_U, tolerances::PLANETARY_LONGITUDES);
    check(ref.name + ": L_Ne", ref.L_NE, args.L_Ne, tolerances::PLANETARY_LONGITUDES);
    check(ref.name + ": pa", ref.PA, args.pa, tolerances::PLANETARY_LONGITUDES);

    // 3. Precession Angles
    auto prec = coords::compute_precession_angles(t_tt);
    check(ref.name + ": gamb", ref.GAMB, prec.gamb, tolerances::PRECESSION_ANGLES);
    check(ref.name + ": phib", ref.PHIB, prec.phib, tolerances::PRECESSION_ANGLES);
    check(ref.name + ": psib", ref.PSIB, prec.psib, tolerances::PRECESSION_ANGLES);
    check(ref.name + ": epsa", ref.EPSA, prec.epsa, tolerances::PRECESSION_ANGLES);

    // 4. Nutation
    auto nut = coords::compute_nutation(t_tt, args);
    // The reference is nut00a; nut06a is it times the IAU 2006 factors
    const double fj2 = -2.7774e-6 * t_tt;
    check(ref.name + ": dpsi", ref.DPSI * (1.0 + 0.4697e-6 + fj2), nut.dpsi, tolerances::NUTATION);
    check(ref.name + ": deps", ref.DEPS * (1.0 + fj2), nut.deps, tolerances::NUTATION);

    // 5. CIP Coordinates
    auto cip = coords::compute_cip_position(t_tt);
    check(ref.name + ": CIP X", ref.CIP_X, cip.X, tolerances::CIP_XY);
    check(ref.name + ": CIP Y", ref.CIP_Y, cip.Y, tolerances::CIP_XY);

    // 6. CIO Locator s
    check(ref.name + ": CIO s", ref.S, cip.s, tolerances::CIO_LOCATOR_S);

    // 7. ERA
    double era = coords::earth_rotation_angle(ut1_jd);
    check(ref.name + ": ERA", ref.ERA, era, tolerances::ERA);

    // 8. TIO Locator s'
    double sp = coords::compute_tio_locator(t_tt);
    check(ref.name + ": TIO s'", ref.SP, sp, tolerances::TIO_LOCATOR_SP);

    // 9. Q Matrix (GCRS to CIRS)
    Matrix3d Q = coords::gcrs_to_cirs_matrix(t_tt);
    for (int i = 0; i < 3; ++i)
        for (int j = 0; j < 3; ++j)
            check(ref.name + ": Q[" + std::to_string(i) + "," + std::to_string(j) + "]",
                  ref.Q_MATRIX[i * 3 + j], Q(i, j), tolerances::Q_MATRIX_ELEMENTS);

    // 10. W Matrix (Polar Motion), also at epochs with zero pole offsets (s' alone)
    {
        double xp_arcsec = ref.XP_RAD / constants::ARCSEC_TO_RAD;
        double yp_arcsec = ref.YP_RAD / constants::ARCSEC_TO_RAD;
        Matrix3d W = coords::tirs_to_itrf_matrix(xp_arcsec, yp_arcsec, t_tt);
        for (int i = 0; i < 3; ++i)
            for (int j = 0; j < 3; ++j)
                check(ref.name + ": W[" + std::to_string(i) + "," + std::to_string(j) + "]",
                      ref.W_MATRIX[i * 3 + j], W(i, j), tolerances::POLAR_MOTION_MATRIX);
    }

    // 11. NPB Matrix
    double psi = prec.psib + nut.dpsi;
    double eps = prec.epsa + nut.deps;
    Matrix3d NPB = coords::build_npb_matrix(prec.gamb, prec.phib, psi, eps);
    for (int i = 0; i < 3; ++i)
        for (int j = 0; j < 3; ++j)
            check(ref.name + ": NPB[" + std::to_string(i) + "," + std::to_string(j) + "]",
                  ref.NPB_MATRIX[i * 3 + j], NPB(i, j), tolerances::MATRIX_ELEMENTS);

    // 12. Full GCRS to ITRF Matrix
    if (ref.XP_RAD != 0.0 || ref.YP_RAD != 0.0) {
        Matrix3d Q_mat = coords::gcrs_to_cirs_matrix(t_tt);
        double cos_era = std::cos(era);
        double sin_era = std::sin(era);
        Matrix3d R;
        R << cos_era, sin_era, 0,
            -sin_era, cos_era, 0,
             0,       0,       1;
        double xp_arcsec = ref.XP_RAD / constants::ARCSEC_TO_RAD;
        double yp_arcsec = ref.YP_RAD / constants::ARCSEC_TO_RAD;
        Matrix3d W_mat = coords::tirs_to_itrf_matrix(xp_arcsec, yp_arcsec, t_tt);
        Matrix3d M = W_mat * R * Q_mat;
        for (int i = 0; i < 3; ++i)
            for (int j = 0; j < 3; ++j)
                check(ref.name + ": GCRS_TO_ITRF[" + std::to_string(i) + "," + std::to_string(j) + "]",
                      ref.GCRS_TO_ITRF[i * 3 + j], M(i, j), tolerances::FULL_MATRIX_ELEMENTS);
    }

    // 13. GMST
    double gmst = coords::gmst(ut1_jd);
    check(ref.name + ": GMST", ref.GMST, gmst, 1e-6);

    return failures;
}

