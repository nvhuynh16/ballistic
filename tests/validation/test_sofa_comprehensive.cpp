int main() {
    std::cout << "======================================================" << std::endl;
    std::cout << "COMPREHENSIVE SOFA/ERFA VALIDATION TEST" << std::endl;
    std::cout << "======================================================" << std::endl;
    std::cout << "\nComparing ballistic library against ERFA reference values." << std::endl;

    TestRunner runner("SOFA/ERFA Comprehensive Validation");

    runner.add_test("j2000_epoch", []() {
        int failures = validate_epoch(make_j2000_ref());
        TEST_ASSERT_MSG(failures == 0,
            "J2000 epoch: " + std::to_string(failures) + " comparisons failed");
    });

    runner.add_test("sentinel1_2016_epoch", []() {
        int failures = validate_epoch(make_sentinel1_ref());
        TEST_ASSERT_MSG(failures == 0,
            "Sentinel1_2016 epoch: " + std::to_string(failures) + " comparisons failed");
    });

    runner.add_test("champ_2005_epoch", []() {
        int failures = validate_epoch(make_champ_ref());
        TEST_ASSERT_MSG(failures == 0,
            "CHAMP_2005 epoch: " + std::to_string(failures) + " comparisons failed");
    });

    runner.add_test("recent_2024_epoch", []() {
        int failures = validate_epoch(make_recent_ref());
        TEST_ASSERT_MSG(failures == 0,
            "Recent_2024 epoch: " + std::to_string(failures) + " comparisons failed");
    });

    runner.add_test("historical_1990_epoch", []() {
        int failures = validate_epoch(make_historical_ref());
        TEST_ASSERT_MSG(failures == 0,
            "Historical_1990 epoch: " + std::to_string(failures) + " comparisons failed");
    });

    runner.run();
    return print_final_summary();
}
