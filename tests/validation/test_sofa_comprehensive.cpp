// =============================================================================
// Comprehensive SOFA/ERFA Validation Test
// =============================================================================
//
// Compares every step of the Earth-rotation chain (fundamental arguments,
// precession, nutation, the celestial pole coordinates, the Earth rotation angle,
// polar motion, and the full GCRS-to-ITRF matrix, i.e. inertial to Earth-fixed)
// with reference values computed by ERFA, the open-source edition of the IAU's
// SOFA library. The values and the per-quantity tolerances live in
// sofa_reference_values.hpp (generated by a Python script that is not part of
// this repository); each tolerance there says why it is set where it is. One test
// cell per epoch; a cell fails if any quantity is outside its tolerance.
// =============================================================================

